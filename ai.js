// 線の形式は draw.js と同じ：{ c: 色, w: 太さ, e: 0, p: [x0, y0, x1, y1, ...] }

const BLACK = '#1e1e1e', RED = '#e53935', ORANGE = '#fb8c00', YELLOW = '#f9a825', GREEN = '#43a047';
const BLUE = '#1e88e5', SKY = '#4fc3f7', PINK = '#ec6a9c', BROWN = '#795548', GRAY = '#8a8f98';

const S = (c, w, p) => ({ c, w, e: 0, p: p.map(Math.round) });

// だ円（a0〜a1 度の弧）。0度が右、90度が下
function ell(cx, cy, rx, ry, c, w = 12, a0 = 0, a1 = 360, n = 48) {
  const p = [];
  for (let i = 0; i <= n; i++) {
    const a = (a0 + (a1 - a0) * i / n) * Math.PI / 180;
    p.push(cx + rx * Math.cos(a), cy + ry * Math.sin(a));
  }
  return S(c, w, p);
}

// 折れ線（点を細かく足して、少しずつ描けるようにする）
function ln(pts, c, w = 12, closed = false) {
  const list = closed ? [...pts, pts[0]] : pts;
  const p = [];
  for (let i = 0; i < list.length - 1; i++) {
    const [x1, y1] = list[i], [x2, y2] = list[i + 1];
    const n = Math.max(2, Math.ceil(Math.hypot(x2 - x1, y2 - y1) / 25));
    for (let j = 0; j < n; j++) p.push(x1 + (x2 - x1) * j / n, y1 + (y2 - y1) * j / n);
  }
  p.push(...list[list.length - 1]);
  return S(c, w, p);
}

const dot = (x, y, c = BLACK, w = 26) => S(c, w, [x, y]);
const box = (x1, y1, x2, y2, c, w = 12) => ln([[x1, y1], [x2, y1], [x2, y2], [x1, y2]], c, w, true);

function wave(x1, x2, y, amp, c, w = 12) {
  const pts = [];
  for (let x = x1; x <= x2; x += 20) pts.push([x, y + amp * Math.sin((x - x1) / 35)]);
  return ln(pts, c, w);
}

