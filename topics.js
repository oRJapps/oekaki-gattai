// お題の文字から、もとのお題（base）と、前につけたことば（mod）を取り出す。知らないお題なら null
export function parseTopic(text) {
  if (typeof text !== 'string' || text.length > 40) return null;
  if (INFO[text]) return { base: text, mod: '', ...INFO[text] };
  for (const kind of Object.keys(MODS)) {
    for (const mod of MODS[kind]) {
      if (!text.startsWith(mod)) continue;
      const base = text.slice(mod.length), info = INFO[base];
      if (info && info.kind === kind) return { base, mod, ...info };
    }
  }
  return null;
}

// ---------- お題がかぶらないようにする ----------
// この端末で出たお題（もとのお題）をおぼえておく（ブラウザの中だけ）。その難易度のお題を全部使いきったら、最初からやり直す。
const SEEN_KEY = 'oekaki_seen_topics';
let seen = [];
try { seen = JSON.parse(localStorage.getItem(SEEN_KEY)) || []; } catch (e) { seen = []; }
if (!Array.isArray(seen)) seen = [];

// お題を「出た」と記録する（組み合わせお題でも、もとのお題で記録する）
export function markTopic(topic) {
  const parsed = parseTopic(topic);
  const base = parsed ? parsed.base : topic;
  if (!seen.includes(base)) seen.push(base);
  try { localStorage.setItem(SEEN_KEY, JSON.stringify(seen)); } catch (e) { /* 保存できなくてもよい */ }
}

// まだ出ていないお題から1つえらぶ。extra：この部屋で出たお題（もとのお題。ほかの人の端末で出たぶんもふくむ）
export function nextTopic(level, extra = new Set()) {
  const all = TOPICS[level] || TOPICS.A;
  let rest = all.filter((t) => !seen.includes(t) && !extra.has(t));
  if (!rest.length) {
    // 全部出た：この難易度のぶんだけ記録を消す。直前のお題だけは、つづけて出ないようにする
    const last = seen[seen.length - 1];
    seen = seen.filter((t) => !all.includes(t));
    rest = all.filter((t) => t !== last && !extra.has(t));
    if (!rest.length) rest = all.filter((t) => t !== last);
  }
  const base = pick(rest);
  const kind = INFO[base].kind;
  if (MODS[kind] && Math.random() < (COMBO_RATE[level] || 0)) return pickMod(kind) + base;
  return base;
}

// いままでに出たお題の数（その難易度で）
export function topicProgress(level) {
  const all = TOPICS[level] || TOPICS.A;
  return { used: all.filter((t) => seen.includes(t)).length, total: all.length };
}
